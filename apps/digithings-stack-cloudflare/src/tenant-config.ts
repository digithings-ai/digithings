/**
 * Tenant corpus map: the read path for the `TENANT_CONFIG` Cloudflare KV
 * namespace, projected into the one shape the container consumes.
 *
 * DIG-3699 (leaf 1.7 of the repo-split epic DIG-3518, goal G07).
 *
 * WHY THIS EXISTS
 * Chris, 2026-10-15 01:26: tenant configuration lives in Cloudflare KV only,
 * and nothing syncs it from a repo file. The consumers are container-side
 * Python processes -- digigraph's `corpus_routing._parse_map` and digivault's
 * `tenant_scope` -- which receive it as the `DIGI_TENANT_CORPUS_MAP`
 * environment variable. So the Worker must read KV and SERIALISE the result
 * into that variable. This module is that projection, and nothing else.
 *
 * THE SHAPE MISMATCH (measured, not assumed)
 *   KV value   = `DIGICHAT_EMBED_TENANTS`, an object KEYED BY HOST:
 *                `{ "<host>": { slug, token, backend: { digisearchIndex,
 *                              vaultPathPrefix, ... }, ...chrome } }`
 *   container  = `DIGI_TENANT_CORPUS_MAP`, an object KEYED BY SLUG:
 *                `{ "<slug>": { digisearchIndex, vaultPathPrefix,
 *                              researchSystemPrompt? } }`
 * The read path therefore cannot pass the KV bytes through; it has to project.
 * The projection mirrors `extract_embed_corpus()` in
 * `scripts/check_tenant_corpus_map.py` -- which reduces the compose file's
 * `DIGICHAT_EMBED_TENANTS` for the same comparison -- so the two agree by
 * construction on which entries survive.
 *
 * PRECEDENCE (highest first)
 *   1. the KV namespace, when bound and readable;
 *   2. `DIGI_TENANT_CORPUS_MAP` from wrangler `[vars]`, the interim source;
 *   3. `DIGITHINGS_ONLY_CORPUS_MAP`, first-party only.
 * Arm 2 is NOT this leaf's to remove. `wrangler.toml` `[vars]` still carries the
 * live OCC entry and the `TENANT_CONFIG` namespace does not exist yet, so
 * deleting arm 2 now would strip tenant config off the deployed Worker. It is
 * removed by the scrub that owns the corpus-map literal (DIG-3689). Arms are
 * REPLACED, not merged: merging would keep a client tenant alive from a source
 * that is supposed to have been retired, which is the fail-open direction.
 *
 * WHY `index.ts` IS NOT WIRED YET
 * `scripts/check_tenant_corpus_map.py` locates the fallback literal with
 * `_FALLBACK_RE`, a regex that pins the EXACT source shape of the
 * `DIGI_TENANT_CORPUS_MAP:` line in `index.ts`. Replacing that literal's `??`
 * arm with this module makes the regex miss, and the drift gate then fails on
 * an unreadable blob rather than on real drift. The literal and that regex are
 * the same scrub's to change, so one owner edits both -- see the DIG-3689 note.
 * Wiring is then one line in `index.ts`:
 *
 *     DIGI_TENANT_CORPUS_MAP: (await tenantCorpusJson(workerEnv)) ?? DIGITHINGS_ONLY_CORPUS_JSON
 *
 * where `workerEnv.TENANT_CONFIG` is the KV binding. That binding is a
 * Cloudflare account change and is outside this ticket's hard limits.
 *
 * FAIL CLOSED, EVERYWHERE
 * An unbound namespace, a KV read that throws, malformed JSON, a non-object
 * document and an entry with no backend index all degrade to "no entry for that
 * tenant" -- never to a wider one. The container side treats a known map with an
 * unknown tenant as a refusal (digivault `tenant_scope`), so a partial read
 * narrows reach instead of extending it.
 */

/** Cloudflare KV binding name (wrangler `kv_namespaces` id). */
export const TENANT_CONFIG_BINDING = "TENANT_CONFIG";

/** KV key holding the embed-tenant document. */
export const TENANT_CONFIG_KEY = "DIGICHAT_EMBED_TENANTS";

/** One tenant's corpus routing, as the container-side Python parses it. */
export interface TenantCorpusEntry {
  digisearchIndex?: string;
  vaultPathPrefix?: string;
  researchSystemPrompt?: string;
}

/** Slug-keyed corpus map: the `DIGI_TENANT_CORPUS_MAP` wire shape. */
export type TenantCorpusMap = Record<string, TenantCorpusEntry>;

/**
 * The first-party tenant only, used when neither KV nor `[vars]` yields
 * anything. Digithings must keep a corpus whether or not a client tenant is
 * configured, so this is the floor rather than an empty map: an empty map makes
 * every tenant unknown, which the container reads as a refusal.
 */
export const DIGITHINGS_ONLY_CORPUS_MAP: TenantCorpusMap = {
  digithings: {
    digisearchIndex: "digithings_docs",
    vaultPathPrefix: "clients/digithings",
  },
};

/** `DIGITHINGS_ONLY_CORPUS_MAP` pre-serialised for the container env var. */
export const DIGITHINGS_ONLY_CORPUS_JSON = JSON.stringify(DIGITHINGS_ONLY_CORPUS_MAP);

/** Corpus fields carried across, matching `_FIELDS` in the drift gate. */
const CORPUS_FIELDS = ["digisearchIndex", "vaultPathPrefix"] as const;

/**
 * The single KV method this module needs. Narrow on purpose: it keeps the unit
 * tests off the full workers-types surface (`Env` is cast in `index.ts`, not
 * generated by `wrangler types`) and it documents the exact dependency.
 */
export interface TenantConfigStore {
  get(key: string): Promise<string | null>;
}

/** Which arm of the precedence chain answered. Diagnostics only -- never auth. */
export type TenantCorpusSource = "kv" | "legacy-vars" | "fallback";

export interface ResolvedTenantConfig {
  /** Serialised `DIGI_TENANT_CORPUS_MAP` for the container environment. */
  json: string;
  /** Parsed form of `json`; same object, no re-parse needed by the caller. */
  map: TenantCorpusMap;
  source: TenantCorpusSource;
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** JSON parse that yields `undefined` instead of throwing. */
function parseJson(raw: string | null | undefined): unknown {
  if (typeof raw !== "string" || raw.trim() === "") return undefined;
  try {
    return JSON.parse(raw);
  } catch {
    return undefined;
  }
}

/**
 * Project the host-keyed embed-tenant document onto the slug-keyed corpus map.
 *
 * Mirrors `extract_embed_corpus()`: an entry survives only when it is an
 * object, carries a `backend` object with a non-blank `digisearchIndex`, and
 * carries a non-blank string `slug`. Everything else is dropped, so a
 * half-configured or malformed tenant never becomes a reachable one.
 *
 * One deliberate divergence from the Python reducer: a non-string
 * `vaultPathPrefix` becomes `""` here, where `str(value)` would yield e.g.
 * `"None"` or `"123"`. A stringified sentinel can be mistaken downstream for a
 * configured prefix; an empty string cannot.
 */
export function projectEmbedTenantsToCorpusMap(document: unknown): TenantCorpusMap {
  if (!isPlainObject(document)) return {};
  const projected: TenantCorpusMap = {};
  for (const entry of Object.values(document)) {
    if (!isPlainObject(entry)) continue;
    const backend = entry["backend"];
    if (!isPlainObject(backend)) continue;
    const index = backend["digisearchIndex"];
    if (typeof index !== "string" || index.trim() === "") continue;
    const slug = entry["slug"];
    if (typeof slug !== "string" || slug.trim() === "") continue;

    const corpus: TenantCorpusEntry = { digisearchIndex: index };
    for (const field of CORPUS_FIELDS) {
      if (field === "digisearchIndex") continue;
      const value = backend[field];
      corpus[field] = typeof value === "string" ? value : "";
    }
    // Field name is a PROPOSAL, not a settled layout: DIG-3567 describes the
    // `occ.digithings.ai` KV entry as "token + backend.digisearchIndex +
    // chrome" and names no prompt field, while the 2112-char OCC research
    // prompt exists today only in the corpus map. Carried when present so a KV
    // value that does carry one loses nothing; its name is carded, not assumed.
    const prompt = backend["researchSystemPrompt"];
    if (typeof prompt === "string" && prompt !== "") {
      corpus.researchSystemPrompt = prompt;
    }
    projected[slug.trim()] = corpus;
  }
  return projected;
}

/** Parse a `DIGI_TENANT_CORPUS_MAP` value (the `[vars]` legacy arm). */
export function parseCorpusMapJson(raw: string | null | undefined): TenantCorpusMap | undefined {
  const parsed = parseJson(raw);
  if (!isPlainObject(parsed)) return undefined;
  const out: TenantCorpusMap = {};
  for (const [slug, value] of Object.entries(parsed)) {
    if (!isPlainObject(value)) continue;
    out[slug] = value as TenantCorpusEntry;
  }
  return Object.keys(out).length > 0 ? out : undefined;
}

function nonEmpty(map: TenantCorpusMap | undefined): map is TenantCorpusMap {
  return map !== undefined && Object.keys(map).length > 0;
}

/**
 * Resolve the effective corpus map: KV, then the legacy `[vars]` string, then
 * the first-party-only constant. Never throws.
 */
export async function readTenantConfig(env: {
  store?: TenantConfigStore;
  legacyJson?: string;
}): Promise<ResolvedTenantConfig> {
  const legacy = parseCorpusMapJson(env.legacyJson);

  if (env.store) {
    try {
      const projected = projectEmbedTenantsToCorpusMap(
        parseJson(await env.store.get(TENANT_CONFIG_KEY)),
      );
      if (nonEmpty(projected)) {
        return { json: JSON.stringify(projected), map: projected, source: "kv" };
      }
      // Bound but empty or unreadable: degrade to the next arm rather than
      // serving a half-configured tenant set.
    } catch {
      // KV read failed: fail closed to the next arm.
    }
  }

  if (nonEmpty(legacy)) {
    return { json: JSON.stringify(legacy), map: legacy, source: "legacy-vars" };
  }
  return {
    json: DIGITHINGS_ONLY_CORPUS_JSON,
    map: DIGITHINGS_ONLY_CORPUS_MAP,
    source: "fallback",
  };
}

/**
 * Per-isolate cache around {@link readTenantConfig}. One KV read per TTL per
 * isolate, so a hot route does not pay a KV round trip per request. The TTL is
 * short because the content is tenant routing: a stale value narrows or
 * widens reach for at most this long.
 */
export const TENANT_CONFIG_TTL_MS = 60_000;

let cached: { at: number; value: ResolvedTenantConfig } | null = null;

/** Cached {@link readTenantConfig}. `now` is injected so the TTL is testable. */
export async function cachedTenantConfig(
  env: { store?: TenantConfigStore; legacyJson?: string },
  now: number,
): Promise<ResolvedTenantConfig> {
  if (cached && now - cached.at < TENANT_CONFIG_TTL_MS) return cached.value;
  const value = await readTenantConfig(env);
  cached = { at: now, value };
  return value;
}

/** Drop the per-isolate cache. Exported for tests, and for nothing else. */
export function resetTenantConfigCache(): void {
  cached = null;
}
