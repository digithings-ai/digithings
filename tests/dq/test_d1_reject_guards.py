"""DIG-2894: the D1 append-only guards must cover every Postgres reject_* guard.

The guard DDL is generated by ``scripts/gen_d1_reject_guards.py`` from the
Postgres migrations. A generated artefact is only trustworthy if something can
*disprove* it, so these tests re-derive the expected coverage from the
migrations with independently written parsing and assert the artefact matches
one-for-one.
"""
from __future__ import annotations

import pathlib
import re
import subprocess
import sys

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
MIGRATIONS_DIR = REPO_ROOT / "digiquant" / "supabase" / "migrations"
ARTEFACT = REPO_ROOT / "digiquant" / "src" / "digiquant" / "d1_reject_guards.sql"
GENERATOR = REPO_ROOT / "scripts" / "gen_d1_reject_guards.py"

EXPECTED_GUARD_FUNCTIONS = 19


# --------------------------------------------------------------------------
# Independent re-derivation. Deliberately written separately from the generator
# so a parsing regression in one does not silently agree with the other.
# --------------------------------------------------------------------------
def _migrations() -> list[pathlib.Path]:
    files = sorted(MIGRATIONS_DIR.glob("*.sql"))
    assert files, f"no migrations found under {MIGRATIONS_DIR}"
    return files


def _clean(path: pathlib.Path) -> str:
    return re.sub(r"--[^\n]*", "", path.read_text(encoding="utf-8"))


def pg_guard_functions() -> set[str]:
    """Every reject_*_mutation trigger function defined in Postgres."""
    names: set[str] = set()
    for path in _migrations():
        for m in re.finditer(
            r"CREATE OR REPLACE FUNCTION\s+(?:public\.)?"
            r"(reject_[a-z0-9_]*_mutation)\s*\(\s*\)\s*RETURNS\s+trigger",
            _clean(path),
            re.IGNORECASE,
        ):
            names.add(m.group(1).lower())
    return names


def pg_row_guards() -> dict[tuple[str, str], str]:
    """Map ``(table, op)`` -> guard function for every row-level UPDATE/DELETE guard.

    Postgres writes ``BEFORE UPDATE OR DELETE ON t FOR EACH ROW``: the operations
    are a comma-free OR-list, so the parse has to split the whole list. Parsing
    only the first operation silently drops half the coverage, which is precisely
    how an earlier revision of this work reported 4 triggers instead of 62.
    """
    out: dict[tuple[str, str], str] = {}
    for path in _migrations():
        sql = _clean(path)
        for m in re.finditer(
            r"CREATE\s+TRIGGER\s+[\"a-z0-9_]+\s+BEFORE\s+"
            r"((?:INSERT|UPDATE|DELETE|TRUNCATE)(?:\s+OR\s+(?:INSERT|UPDATE|DELETE|TRUNCATE))*)"
            r"\s+ON\s+(?:public\.)?\"?([a-z0-9_]+)\"?"
            r"(?:(?!\bCREATE\b).)*?FOR\s+EACH\s+ROW"
            r"(?:(?!\bCREATE\b).)*?"
            r"EXECUTE\s+(?:PROCEDURE|FUNCTION)\s+(?:public\.)?"
            r"(reject_[a-z0-9_]*_mutation)\s*\(\s*\)",
            sql,
            re.IGNORECASE | re.DOTALL,
        ):
            table = m.group(2).lower()
            guard = m.group(3).lower()
            for op in re.split(r"\s+OR\s+", m.group(1), flags=re.IGNORECASE):
                op = op.upper()
                if op in ("UPDATE", "DELETE"):
                    out[(table, op)] = guard
    return out


def pg_statement_guards() -> int:
    """How many FOR EACH STATEMENT guard triggers Postgres installs."""
    n = 0
    for path in _migrations():
        n += len(re.findall(r"FOR\s+EACH\s+STATEMENT", _clean(path), re.IGNORECASE))
    return n


def artefact_triggers(path: pathlib.Path = ARTEFACT) -> dict[tuple[str, str], str]:
    """Map ``(table, op)`` -> abort message for each D1 trigger in the artefact."""
    out: dict[tuple[str, str], str] = {}
    sql = path.read_text(encoding="utf-8")
    for m in re.finditer(
        r'CREATE TRIGGER IF NOT EXISTS\s+"([a-z0-9_]+?)_append_only_(update|delete)"'
        r"\s*BEFORE\s+(UPDATE|DELETE)\s+ON\s+\"([a-z0-9_]+)\"\s*BEGIN\s*"
        r"SELECT RAISE\(ABORT,\s*'(?P<msg>(?:[^']|'')*)'\);",
        sql,
        re.IGNORECASE,
    ):
        out[(m.group(4).lower(), m.group(3).upper())] = m.group("msg").replace("''", "'")
    return out


# --------------------------------------------------------------------------
# Tests
# --------------------------------------------------------------------------
def test_artefact_exists_and_has_guards():
    assert ARTEFACT.exists(), f"{ARTEFACT} missing; run scripts/gen_d1_reject_guards.py"
    assert artefact_triggers(), "artefact parsed to zero triggers (regex or file regressed)"


def test_guard_function_count_matches_the_ticket():
    names = pg_guard_functions()
    assert len(names) == EXPECTED_GUARD_FUNCTIONS, (
        f"Postgres defines {len(names)} reject_*_mutation guard functions, "
        f"ticket DIG-2894 says {EXPECTED_GUARD_FUNCTIONS}"
    )


def test_artefact_is_in_sync_with_the_migrations():
    """--check regenerates and compares: catches a stale or hand-edited artefact."""
    proc = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"],
        capture_output=True, text=True, cwd=REPO_ROOT,
    )
    assert proc.returncode == 0, (
        f"artefact is out of sync with the migrations (rc={proc.returncode})\n"
        f"{proc.stdout}{proc.stderr}"
    )


def test_every_postgres_row_guard_has_a_d1_trigger():
    expected = pg_row_guards()
    actual = artefact_triggers()
    assert expected, "parsed zero Postgres row guards (parser regression?)"
    assert actual, "parsed zero D1 triggers (parser regression?)"
    missing = sorted(set(expected) - set(actual))
    extra = sorted(set(actual) - set(expected))
    assert not missing, f"{len(missing)} Postgres guards have no D1 trigger: {missing[:10]}"
    assert not extra, f"{len(extra)} D1 triggers guard nothing in Postgres: {extra[:10]}"


def test_d1_trigger_count_matches_the_parsed_row_guard_count():
    """Exact count equality - this is the assertion that catches a dropped OR-list."""
    assert len(artefact_triggers()) == len(pg_row_guards())


def test_guards_are_append_only_not_insert_blocking():
    """Postgres guards are BEFORE UPDATE OR DELETE: INSERT must stay legal in D1.

    Emitting BEFORE INSERT here would invert the guarantee - it would make the
    table read-only instead of append-only, and block every legitimate write.
    """
    sql = ARTEFACT.read_text(encoding="utf-8")
    assert not re.search(r"BEFORE\s+INSERT\s+ON", sql, re.IGNORECASE), (
        "artefact blocks INSERT; the Postgres guards are append-only (UPDATE/DELETE)"
    )


def test_abort_message_is_non_empty_and_carries_the_guard_text():
    for (table, op), msg in artefact_triggers().items():
        assert msg.strip(), f"empty RAISE(ABORT) message for {table} {op}"
        assert "append-only" in msg.lower(), (
            f"{table} {op} abort message does not say the table is append-only: {msg!r}"
        )


def test_worker_side_obligations_are_enumerated_not_dropped():
    """Postgres FOR EACH STATEMENT / TRUNCATE have no SQLite equivalent.

    They cannot be expressed as a trigger, so they must be listed as worker-side
    obligations. Silence here would mean silently losing that coverage.
    """
    statement_triggers = pg_statement_guards()
    assert statement_triggers, "no FOR EACH STATEMENT guards found (parser regression?)"
    sql = ARTEFACT.read_text(encoding="utf-8")
    section = sql.split("Worker-side obligations")[-1]
    listed = len(re.findall(r"^--\s+\w+\s+ON\s+", section, re.MULTILINE))
    assert listed >= statement_triggers, (
        f"{statement_triggers} statement-level Postgres guards but only {listed} "
        "listed as worker-side obligations"
    )


def test_coverage_check_can_fail_when_a_trigger_is_removed(monkeypatch, tmp_path):
    """Non-vacuity control.

    Delete one D1 trigger from a scratch copy and prove the coverage assertion
    above actually dies. Without this, a check that passes because it parses to
    an empty set would look identical to a correct one.
    """
    full = artefact_triggers()
    assert full, "artefact parsed to zero triggers"
    victim = sorted(full)[0]
    assert len(full) > 1, "artefact has a single trigger; the control needs more"

    pruned = ARTEFACT.read_text(encoding="utf-8")
    pruned = re.sub(
        r'CREATE TRIGGER IF NOT EXISTS "[a-z0-9_]+_append_only_(?:update|delete)"'
        r"\s*BEFORE\s+(?:UPDATE|DELETE)\s+ON\s+\"[a-z0-9_]+\"\s*BEGIN\s*"
        r"SELECT RAISE\(ABORT,\s*'(?:[^']|'')*'\);\s*END;\s*",
        "",
        pruned,
        count=1,
    )
    scratch = tmp_path / "d1_reject_guards.sql"
    scratch.write_text(pruned, encoding="utf-8")
    assert len(pruned) < len(ARTEFACT.read_text(encoding="utf-8")), "control made no edit"
    assert victim not in artefact_triggers(scratch), (
        f"control removed {sorted(full)[:1]} but not its intended victim {victim}"
    )

    # Re-parse the pruned copy and confirm the missing-trigger assertion fires.
    # Pass the path in rather than rebinding the module global: assigning to a
    # global inside a function makes it local for the WHOLE function.
    expected, actual = pg_row_guards(), artefact_triggers(scratch)
    missing = set(expected) - set(actual)
    assert missing, "control FAILED to detect a removed trigger; the check is vacuous"
