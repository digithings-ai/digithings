def test_no_columns_beyond_the_contract(columns: dict[str, str]) -> None:
    """The upsert enumerates these six by name and ignores anything else.

    A seventh column added here is at best never written; if it is NOT NULL without a
    default it fails every publisher run instead. Update the edge function and
    ``priceRowToLive`` in the same change, then extend EXPECTED_COLUMNS.
    """
    assert set(columns) == {name for name, _, _ in EXPECTED_COLUMNS}, (
        f"column set drifted from the contract: {sorted(columns)}"
    )
