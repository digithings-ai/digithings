"""The stack deploy lane packages the image inputs before it builds the image (DIG-4711).

`infra/docker/Dockerfile.digithings-stack-cloudflare` COPYs three paths under
`image-packages/stack/`, and the image build context is the repository root
(`image_build_context = "../.."`). `image-packages/` is GENERATED by
`scripts/package_r5_image_inputs.py` and is gitignored (`.gitignore`
`/image-packages/`), so a CI checkout never carries it and the build dies
computing its cache key, before a single build step runs:

    ERROR: failed to build: failed to solve: failed to compute cache key:
    failed to calculate checksum of ref ...:
    "/image-packages/stack/digisearch-seeds": not found

(run 39485748555, 2026-10-20 - the third independent failure in that lane
after the lockfile and the secret name).

These assertions are about the SHAPE of the lane, over the workflow's own
document, over the action it calls, over the Dockerfile it builds and over the
generator that produces the tree - because the failure is invisible to
`actionlint` and to every other test in this directory: a job without a
packaging step is valid YAML that lints clean and would still ship a lane that
cannot build its image.

The loops are the point. The Dockerfile's COPY list is checked against the
guard that runs before the build, against the paths the generator writes, and
against the packages the image installs; the workflow's job list is derived
rather than named, so a NEW job that builds the image is covered by the same
assertion that covers the deploy job.
"""

from __future__ import annotations

import fnmatch
import importlib.util
import re
from pathlib import Path

import pytest
import yaml

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]
WORKFLOW = REPO_ROOT / ".github" / "workflows" / "deploy-digithings-stack-cloudflare.yml"
ACTION = REPO_ROOT / ".github" / "actions" / "package-stack-image-inputs" / "action.yml"
DOCKERFILE = REPO_ROOT / "infra" / "docker" / "Dockerfile.digithings-stack-cloudflare"
DOCKERIGNORE = REPO_ROOT / ".dockerignore"
GENERATOR = REPO_ROOT / "scripts" / "package_r5_image_inputs.py"
SEEDS = REPO_ROOT / "digisearch" / "seeds"

#: The local action that packages the tree. A remote reference would package
#: something else than this repository's Dockerfile asks for.
ACTION_REF = "./.github/actions/package-stack-image-inputs"

#: The step that makes wrangler build the image. A job that runs it is a job
#: that needs the packaged tree.
DEPLOY_COMMAND = "npm run deploy --workspace digithings-stack-cloudflare"


def _doc() -> dict:
    return yaml.safe_load(WORKFLOW.read_text(encoding="utf-8"))


def _action() -> dict:
    return yaml.safe_load(ACTION.read_text(encoding="utf-8"))


def _steps(job: dict) -> list[dict]:
    return job["steps"]


def _index_of_ref(job: dict, ref: str) -> int:
    """The index of the step that uses ``ref``; -1 when the job has no such step."""
    for index, step in enumerate(_steps(job)):
        if str(step.get("uses", "")) == ref:
            return index
    return -1


def _index_of_run(job: dict, needle: str) -> int:
    """The index of the first step whose ``run`` contains ``needle``; -1 when none."""
    for index, step in enumerate(_steps(job)):
        if needle in str(step.get("run", "")):
            return index
    return -1


def _action_script() -> str:
    """The packaging step's shell script, comments stripped.

    Comments are stripped so prose that merely names a path cannot satisfy
    the assertions below: the guard has to NAME the path in executable text.
    """
    steps = _action()["runs"]["steps"]
    scripts = [str(step.get("run", "")) for step in steps if "run" in step]
    assert len(scripts) == 1, "the action must have exactly one run step"
    return re.sub(r"#.*$", "", scripts[0], flags=re.M)


def _dockerfile_copy_sources() -> list[str]:
    """Every source path the Dockerfile COPYs that lives under image-packages/."""
    sources: list[str] = []
    for line in DOCKERFILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line.startswith("COPY "):
            continue
        tokens = [token for token in line.split()[1:] if not token.startswith("--")]
        if len(tokens) < 2:
            continue
        for source in tokens[:-1]:
            if source.startswith("image-packages/"):
                sources.append(source)
    return sources


def _guarded_paths(script: str) -> set[str]:
    """The paths the action's guard loop actually checks for existence.

    Parsed out of the `for path in ... do` block rather than searched for as
    text: a path that is merely MENTIONED somewhere else in the script (the
    wheels path also appears in the emptiness check below it) must not pass
    for a path the guard checks.
    """
    paths: set[str] = set()
    lines = script.splitlines()
    index = 0
    while index < len(lines):
        if lines[index].strip().startswith("for path in"):
            index += 1
            while index < len(lines):
                token = lines[index].strip().rstrip("\\").strip()
                if token.startswith("do"):
                    break
                if token:
                    paths.add(token)
                index += 1
        index += 1
    return paths


def _dockerfile_wheel_installs() -> set[str]:
    """The packages the Dockerfile installs from the packaged wheels.

    Read out of the ``--find-links /wheels`` install block, so a third-party
    pin elsewhere in the Dockerfile (litellm, searxng) is not counted: only
    the workspace wheels the image installs from image-packages/ are.
    """
    names: set[str] = set()
    spec = r'"([A-Za-z0-9_.-]+)(?:\[[^\]]*\])?==[0-9][^"]*"'
    in_block = False
    for raw in DOCKERFILE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not in_block:
            if "--find-links /wheels" not in line:
                continue
            in_block = True
        names.update(match.group(1) for match in re.finditer(spec, line))
        if not line.endswith("\\"):
            in_block = False
    return names


def _dockerignore_rules() -> list[tuple[str, bool]]:
    rules: list[tuple[str, bool]] = []
    for raw in DOCKERIGNORE.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        negated = line.startswith("!")
        if negated:
            line = line[1:].strip()
        rules.append((line, negated))
    return rules


def _pattern_matches(pattern: str, ancestor: str) -> bool:
    """Whether a .dockerignore pattern matches a path or a directory.

    Docker's matcher is not python's fnmatch: `**` crosses directory
    boundaries, and `**/x` matches a ROOT-level `x` as well as a nested one.
    The model here is deliberately the strict one - it says "excluded" when
    docker would exclude - so a path the guard checks can never read as safe
    because this matcher was more permissive than docker is.
    """
    if "/" not in pattern:
        return fnmatch.fnmatch(ancestor.rsplit("/", 1)[-1], pattern)
    if pattern.startswith("**/"):
        rest = pattern[3:]
        tail = ancestor.split("/")[-1]
        if fnmatch.fnmatch(tail, rest):
            return True
        return fnmatch.fnmatch(ancestor, pattern) or fnmatch.fnmatch(ancestor, "**/" + rest)
    return fnmatch.fnmatch(ancestor, pattern)


def _excluded_by_dockerignore(path: str) -> bool:
    """Whether docker would drop ``path`` from the build context.

    Docker's rules: the last matching pattern wins, a pattern without a slash
    matches a basename at any depth, and a pattern with a slash matches the
    path from the context root. A directory that matches is pruned whole, so
    every ancestor of the path counts.
    """
    parts = path.split("/")
    ancestors = ["/".join(parts[: index + 1]) for index in range(len(parts))]
    excluded = False
    for pattern, negated in _dockerignore_rules():
        for ancestor in ancestors:
            if _pattern_matches(pattern, ancestor):
                excluded = not negated
    return excluded


def _load_generator():
    """The packaging script, imported as a module.

    It is imported rather than shelled out to, so the contract between the
    generator and the Dockerfile can be checked against the SAME list the
    generator writes from.
    """
    spec = importlib.util.spec_from_file_location("package_r5_image_inputs", GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_deploy_job_packages_before_it_deploys() -> None:
    """The build context has to carry image-packages/ when the image is built."""
    job = _doc()["jobs"]["deploy"]
    packaging = _index_of_ref(job, ACTION_REF)
    assert packaging != -1, f"the deploy job does not use {ACTION_REF}"
    deploy = _index_of_run(job, DEPLOY_COMMAND)
    assert deploy != -1, "the deploy job does not deploy the stack"
    assert packaging < deploy, "the deploy job must package the image inputs before it deploys"


def test_the_deploy_gate_packages_too() -> None:
    """The gate is the last job before the production approval, so it proves the packaging."""
    job = _doc()["jobs"]["check-deploy-gate"]
    assert _index_of_ref(job, ACTION_REF) != -1, (
        f"the deploy gate does not use {ACTION_REF}: a broken generator would then be "
        "discovered at a deploy Chris already approved"
    )


def test_the_pull_request_check_packages_too() -> None:
    """The generator is proven in CI before a change can reach main."""
    job = _doc()["jobs"]["check"]
    assert _index_of_ref(job, ACTION_REF) != -1, (
        f"the pull-request check does not use {ACTION_REF}: the generator would first "
        "be exercised at a production deploy"
    )


def test_every_job_that_builds_the_image_packages_it_first() -> None:
    """The job list is DERIVED, so a new build job is covered by the same rule.

    Naming the three jobs would let a fourth one - a dry-run lane, a second
    deploy job - build the image out of a context with no packaged tree, and
    every test here would stay green.
    """
    jobs = _doc()["jobs"]
    builders = {name: job for name, job in jobs.items() if _index_of_run(job, DEPLOY_COMMAND) != -1}
    assert builders, "the workflow no longer builds the image - has the lane changed?"
    for name, job in builders.items():
        packaging = _index_of_ref(job, ACTION_REF)
        deploy = _index_of_run(job, DEPLOY_COMMAND)
        assert packaging != -1, (
            f"the {name} job builds the image but does not use {ACTION_REF}, so its "
            "build context carries no packaged tree"
        )
        assert packaging < deploy, f"the {name} job must package the image inputs before it builds"


def test_the_action_runs_the_stack_scope_of_the_generator() -> None:
    """The scope is this image's, and it is named.

    The full generator also builds the runner project - a fresh, unpinned `uv
    lock` against PyPI - and packs five npm workspaces the stack image never
    installs. A production deploy must not inherit a network-dependent
    resolution step it does not use.
    """
    script = _action_script()
    assert "python3 scripts/package_r5_image_inputs.py --stack-only" in script, (
        "the action does not package the stack image's inputs"
    )
    assert "--npm-only" not in script, (
        "--npm-only packages the digichat image's inputs, not this image's"
    )
    for line in script.splitlines():
        if "package_r5_image_inputs.py" in line and not re.search(
            r"package_r5_image_inputs\.py\s+--", line
        ):
            pytest.fail(
                "the action runs the FULL generator, which builds the runner project and "
                f"packs the npm workspaces the stack image does not install: {line.strip()}"
            )
    assert "python3 scripts/package_r5_image_inputs.py --check-only --stack-only" in script, (
        "the action does not verify the tree it just packaged"
    )


def test_the_stack_scope_never_packs_an_npm_tarball(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The stack scope needs no node, and that is proved, not assumed.

    The generator packs npm tarballs with `npm pack` in its full mode. If the
    stack scope ever packed one, the action would need node - and a caller
    without it would fail at deploy time with "npm: command not found".
    """
    module = _load_generator()
    out = tmp_path / "image-packages"
    monkeypatch.setattr(module, "OUT", out)
    commands: list[list[str]] = []
    monkeypatch.setattr(module, "_run", lambda cmd, cwd=None: commands.append(list(cmd)))

    def fake_build_wheel(package: str, dest: Path) -> Path:
        dest.mkdir(parents=True, exist_ok=True)
        wheel = dest / f"{package.replace('-', '_')}-0.1.0-py3-none-any.whl"
        wheel.write_bytes(b"wheel")
        return wheel

    def fake_export(package: str, extras: tuple[str, ...], dest: Path) -> None:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(f"{package}==0.1.0\n", encoding="utf-8")

    monkeypatch.setattr(module, "_build_wheel", fake_build_wheel)
    monkeypatch.setattr(module, "_export", fake_export)

    assert module.stack_only() == 0
    assert not any(cmd[:2] == ["npm", "pack"] for cmd in commands), (
        f"the stack scope packed an npm tarball: {commands}"
    )
    assert not any(cmd[:1] == ["uv"] and "lock" in cmd for cmd in commands), (
        f"the stack scope ran a uv lock against PyPI: {commands}"
    )
    assert (out / "stack" / "requirements.txt").is_file()
    assert (out / "stack" / "digisearch-seeds").is_dir()
    assert len(list((out / "stack" / "wheels").glob("*.whl"))) == len(module.STACK_PACKAGES)


def test_the_action_sets_up_the_toolchain_the_generator_needs() -> None:
    steps = _action()["runs"]["steps"]
    uses = [str(step.get("uses", "")) for step in steps]
    assert any(u.startswith("actions/setup-python") for u in uses), (
        "the generator reads pyproject.toml with tomllib, so it needs python 3.11+"
    )
    assert any(u.startswith("astral-sh/setup-uv") for u in uses), (
        "the generator builds the wheels and exports the frozen requirement set with uv"
    )


def test_the_guard_covers_every_path_the_dockerfile_copies() -> None:
    """A new COPY under image-packages/ without a matching guard fails here."""
    script = _action_script()
    sources = _dockerfile_copy_sources()
    assert sources, "the Dockerfile copies nothing under image-packages/: has the image changed?"
    guarded = _guarded_paths(script)
    assert guarded, "the action's guard checks no path at all"
    for source in sources:
        assert source in guarded, (
            f"the Dockerfile COPYs {source} but the packaging guard does not check it, "
            "so a missing path would not fail the step"
        )
    assert "::error::" in script, "the guard does not report what is missing"
    assert re.search(r"exit\s+(?:1|\"?\$\{?missing)", script), (
        "the guard reports a missing path but never exits non-zero, so the step would "
        "report success and the build would still die on the same missing path"
    )


def test_the_generator_writes_every_path_the_dockerfile_copies() -> None:
    """The other half of the loop: the guard checks what the generator writes.

    A rename of a generator output would leave the Dockerfile and the guard
    naming the old path, and only the deploy job would notice - after Chris's
    production approval. The generator's own output list closes that loop.
    """
    module = _load_generator()
    written = {f"image-packages/{rel}" for rel in module.STACK_OUTPUTS}
    assert set(_dockerfile_copy_sources()) == written, (
        "the Dockerfile COPYs a path the stack scope does not write, or the stack scope "
        "writes a path the Dockerfile never reads"
    )


def test_the_generator_builds_the_wheels_the_image_installs() -> None:
    """The packages the generator builds are the packages the image installs."""
    module = _load_generator()
    built = {package for package, _extras in module.STACK_PACKAGES}
    installed = _dockerfile_wheel_installs()
    assert installed, "the Dockerfile installs nothing from /wheels - has the image changed?"
    assert built == installed, (
        "the generator builds a different set of workspace wheels than the image "
        f"installs: built {sorted(built)}, installed {sorted(installed)}"
    )


def test_the_guard_expects_the_wheels_the_image_installs() -> None:
    """A partial wheel set is a partial image, so the guard counts them."""
    script = _action_script()
    expected = len(_dockerfile_wheel_installs())
    match = re.search(r'!= "(\d+)"', script)
    assert match, "the guard does not check how many wheels the tree holds"
    assert int(match.group(1)) == expected, (
        f"the guard expects {match.group(1)} wheels but the image installs {expected}"
    )


def test_the_packaged_paths_survive_the_dockerignore_filter() -> None:
    """The guard reads the FILESYSTEM; docker reads the FILTERED context.

    A `.dockerignore` basename rule (`data`, `tests`, `dist`, `scripts`) matches
    at any depth, so a subdirectory named `data` under the seeds would be
    dropped silently: the COPY still succeeds and the image ships an empty
    corpus. Nothing else in the suite would notice.
    """
    for source in _dockerfile_copy_sources():
        assert not _excluded_by_dockerignore(source), (
            f".dockerignore drops {source} from the build context, so the image would "
            "carry no such path even though the guard passed"
        )
    for path in SEEDS.rglob("*"):
        relative = path.relative_to(REPO_ROOT).as_posix()
        packaged = f"image-packages/stack/digisearch-seeds/{relative.split('digisearch/seeds/', 1)[-1]}"
        assert not _excluded_by_dockerignore(packaged), (
            f".dockerignore drops {packaged} from the build context, so the image "
            "would seed a smaller corpus than the tree holds"
        )


def test_the_path_filters_include_the_packaging_action() -> None:
    """The action decides what the image carries, so a change to it must run the lane.

    The frozen lockfile is in the same class: the image installs what
    `uv export --frozen` writes out of it, so a merge that only bumps a
    transitive pin changes the image and matches no filter - it would deploy
    nothing and the image would keep the old pins.

    So is .dockerignore: the image is built from the repository root, so the
    root .dockerignore decides what the build context carries. A merge that
    only edits it changes the image and matches no filter.
    """
    triggers = _doc()[True]
    for trigger in ("push", "pull_request"):
        paths = set(triggers[trigger]["paths"])
        assert ".github/actions/package-stack-image-inputs/action.yml" in paths, (
            f"the {trigger} path filter does not match the packaging action, so a change "
            "to it is never proven in CI and the merge deploys the previous recipe"
        )
        assert "uv.lock" in paths, (
            f"the {trigger} path filter does not match uv.lock, so a merge that only "
            "bumps a transitive pin changes the image and matches no filter: it would "
            "deploy nothing and the image would keep the old pins"
        )
        assert ".dockerignore" in paths, (
            f"the {trigger} path filter does not match .dockerignore, so a merge that "
            "only edits it changes what the build context carries and matches no "
            "filter: it would deploy nothing and the container would keep the old "
            "contents"
        )


def test_a_stack_only_tree_is_refused_by_a_full_check(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """A partial tree must never read as a complete one.

    The stack scope writes the stack image's inputs and says so in the
    provenance's scope. A full check - the one a runner deploy runs - must
    refuse that tree, because a runner deploy built on it would ship an image
    without its wheels.

    The digests are stubbed: the decision under test is about the KEY SETS
    (what the record covers, what the scope covers), and the real digest
    shells out to git once per input path - 72 seconds of subprocesses for a
    question about names.
    """
    module = _load_generator()
    out = tmp_path / "image-packages"
    monkeypatch.setattr(module, "OUT", out)
    monkeypatch.setattr(module, "content_digest", lambda path: "digest")
    out.mkdir(parents=True, exist_ok=True)
    module._write_provenance(module.stack_input_paths(), scope=module.STACK_SCOPE)
    provenance = out / module.PROVENANCE_NAME
    assert module.check_only(scope=module.STACK_SCOPE, provenance=provenance) == 0, (
        "the scoped check must accept the scope it packaged"
    )
    assert module.check_only(provenance=provenance) == 1, (
        "a full check must refuse a tree that carries only the stack image's inputs"
    )


def test_the_deploy_reads_the_secret_that_exists() -> None:
    """The repo secret is CLOUDFLARE_API_TOKEN.

    The lane read CLOUDFLARE_WORKERS_API_TOKEN, which no secret answers, so
    wrangler got an empty token and the production deploy failed on auth (run
    39482995993). #6066 fixed it on main and #6081 broke it again; develop
    carried #6076's preflight on the same dead name, which no deploy could
    ever pass. This pins the name that does exist: run 39490394661 uploaded
    and deployed this Worker with it.
    """
    text = WORKFLOW.read_text(encoding="utf-8")
    code = "\n".join(
        line for line in text.splitlines() if not line.strip().startswith("#")
    )
    assert "CLOUDFLARE_API_TOKEN: ${{ secrets.CLOUDFLARE_API_TOKEN }}" in code
    assert "CLOUDFLARE_WORKERS_API_TOKEN" not in code, (
        "the deploy reads a secret name that does not exist"
    )
