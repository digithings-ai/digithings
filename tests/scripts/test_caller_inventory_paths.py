"""Guards the generated Supabase caller inventory against hand-edits (DIG-4575).

``docs/release/supabase-exit/caller-inventory.md`` is generated by
``scripts/inventory/supabase_caller_inventory.py`` and carries a "do not
hand-edit" header. The generator emits the real tracked paths of the
repository, so every repo path the document names must be spelled exactly the
way the repository spells it.

A brand-token sweep once lowercased one path in that document, which left the
reader with a file that does not exist and was silently reverted by the
generator's next run. This test fails the change that does it, so the
recurrence stops at the pull request instead of reaching the document.

It reads the shipped document and the tracked file names, so it depends on the
shape of this repository on purpose.
"""

import re
import subprocess
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parents[2]
INVENTORY_MD = REPO_ROOT / "docs" / "release" / "supabase-exit" / "caller-inventory.md"

PATH_TOKEN = re.compile(r"`([^`\n]+)`")


def _tracked_paths() -> list[str]:
    proc = subprocess.run(
        ["git", "-C", str(REPO_ROOT), "ls-files"],
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        pytest.skip(f"git ls-files failed in {REPO_ROOT}: {proc.stderr.strip()}")
    return proc.stdout.splitlines()


def test_inventory_names_repo_paths_with_the_exact_tracked_spelling():
    tracked = _tracked_paths()
    assert tracked, "git ls-files returned no tracked path"

    by_lower: dict[str, list[str]] = {}
    for path in tracked:
        by_lower.setdefault(path.lower(), []).append(path)
    top_level = {path.split("/", 1)[0] for path in tracked if "/" in path}

    mismatched = []
    for token in sorted(set(PATH_TOKEN.findall(INVENTORY_MD.read_text()))):
        if "/" not in token or token.split("/", 1)[0] not in top_level:
            continue
        hits = by_lower.get(token.lower(), [])
        if hits and token not in hits:
            mismatched.append(f"{token} (tracked as {', '.join(hits)})")

    assert not mismatched, (
        "caller-inventory.md names repo paths that do not match the tracked "
        f"file names: {'; '.join(mismatched)}"
    )
