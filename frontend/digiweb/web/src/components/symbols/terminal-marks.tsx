/**
 * Terminal brand marks — the `digi` prompt lockup and the hairline wordmark.
 *
 * The house identity reads as a terminal line caught mid-prompt: the module
 * name followed by a filled block cursor. The cursor is not a new shape — it is
 * the `.term-cursor` geometry from @digithings/design (site.css), 0.6em wide by
 * 1.05em tall sitting at vertical-align -0.16em. 0.6em is exactly one Geist Mono
 * advance, so the cursor occupies one character cell and the lockup sits on the
 * mono grid without fudging.
 *
 * Three exports, each matching the weight of the surface it imitates:
 *
 * - TerminalMark: outlined `digi` + cursor, filled in currentColor. Geist Mono
 *   400 — the weight terminal text actually renders at, since .term-body /
 *   .cmdline / .app-input-field set no font-weight and inherit
 *   body{font-weight:400}. Outlined rather than text because this same artwork
 *   is the favicon source and must not depend on a loaded font. `variant`
 *   selects the full `digi` lockup or the compact `d` reduction; use compact
 *   below ~64px, where the full lockup's five character cells close up.
 * - TerminalWordmark: the default wordmark. Deliberately TEXT, not outlined —
 *   it is plain mono at tracking 0 with no overlapping contours to preserve, so
 *   outlining would ship ~9KB of path data for a glyph-identical result
 *   wherever Geist Mono is loaded. Carries token-backed utilities, so consumers
 *   need an `@source "<path-to>/digiweb/web/src/components/symbols"` line.
 *   Deliberately ONE TONE — `text-ink`, never `--accent` — regardless of any
 *   surrounding `.accent-<module>` livery scope: it reads as a real shell
 *   prompt, and real terminal output does not recolor by module (`.term-body`
 *   is one ink color throughout). See terminal-marks.render.test.tsx's "does
 *   not dress the suffix in the accent" case.
 * - HairlineWordmark: the display cut, replicating the footer colophon's
 *   `.colo-word` — stroke 0.538% of the em (a 1px line on a ~186px glyph),
 *   ink at 30%, tracking -0.05em, Geist Mono 500. FULL-BLEED ONLY. The stroke
 *   scales with the art, so the floor is on the em, not on the rendered width:
 *   below an em of ~173px it goes sub-pixel and greys out. For `digithings`
 *   (10 cells at 0.6em) that means a rendered width of ~1036px before the
 *   stroke reaches one device pixel; ~933px for `digiquant`. This is the
 *   colophon's own scale — `.colo-word` is `clamp(3rem, 15.5vw, 15rem)`, i.e.
 *   ~186px em and a ~1116px word at a 1200px viewport. Anywhere narrower, use
 *   TerminalWordmark instead; do not shrink this one to fit.
 *
 * The hairline paths are outlined from the VARIABLE font, contours left
 * overlapping and un-booleaned. That is load-bearing, not an oversight: stroked,
 * those overlaps are what give the `t` its crossing grid and the `d` and `i`
 * their stem spurs. Never run a boolean union / "remove overlap" / SVG
 * "simplify paths" pass over this data, and never regenerate it from a static
 * cut — the static `t` has one merged contour where the variable font has two,
 * and the crossings vanish silently.
 *
 * No CSS ships with this family; TerminalMark and HairlineWordmark are pure
 * SVG in currentColor, so whatever sets `color` in the ancestor chain dresses
 * them — note an `.accent-<module>` scope alone does NOT: it only exposes
 * `--accent` as a custom property, it does not set `color` itself, so a
 * consumer wanting the livery effect must set `color: var(--accent)`
 * explicitly somewhere between the scope and the mark (see symbols.css's
 * `.sym-hairline--accent` for this reference site's opt-in pattern).
 * TerminalWordmark is the deliberate exception — it never reads --accent at
 * all, see its own bullet above.
 */
