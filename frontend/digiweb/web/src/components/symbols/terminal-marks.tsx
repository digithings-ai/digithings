export interface TerminalMarkProps {
  /** Rendered square size in px. Default 22. */
  size?: number;
  className?: string;
  /** Accessible name (renders a `<title>` + role="img"); omitted → decorative. */
  title?: string;
  /** `full` = `digi` + cursor; `compact` = `d` + cursor. Use compact below ~64px. */
  variant?: "full" | "compact";
}

export function TerminalMark({
  size = 22,
  className,
  title,
  variant = "full",
}: TerminalMarkProps) {
  const paths = variant === "compact" ? MARK_COMPACT : MARK_FULL;
  const cursor = MARK_CURSOR[variant];
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 100 100"
      fill="currentColor"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : "true"}
      focusable="false"
      className={["terminal-mark", className].filter(Boolean).join(" ")}
    >
      {title ? <title>{title}</title> : null}
      {paths.map((d) => (
        <path key={d.slice(0, 24)} d={d} />
      ))}
      <rect {...cursor} />
    </svg>
  );
}

export interface TerminalWordmarkProps {
  /** The module suffix after `digi` — e.g. "things", "quant". */
  suffix: ReactNode;
  /** Defaults to `digi`. */
  prefix?: ReactNode;
  className?: string;
}

export function TerminalWordmark({
  suffix,
  prefix = "digi",
  className,
}: TerminalWordmarkProps) {
  return (
    <span
      className={[
        "terminal-wordmark",
        "font-mono text-[1.25rem] font-normal tracking-normal text-ink",
        className,
      ]
        .filter(Boolean)
        .join(" ")}
    >
      {prefix}
      {suffix}
    </span>
  );
}

