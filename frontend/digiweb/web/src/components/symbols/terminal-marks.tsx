/** Stroke as a fraction of the em — a 1px line on a ~186px glyph (site.css). */
const HAIRLINE_STROKE_RATIO = 1 / 186;
const HAIRLINE_EM = 1000;

export interface HairlineWordmarkProps {
  /** Which wordmark to draw. */
  word: keyof typeof HAIRLINE;
  className?: string;
  /** Accessible name (renders a `<title>` + role="img"); omitted → decorative. */
  title?: string;
}

export function HairlineWordmark({ word, className, title }: HairlineWordmarkProps) {
  const spec = HAIRLINE[word];
  return (
    <svg
      viewBox={spec.viewBox}
      fill="none"
      stroke="currentColor"
      strokeOpacity={0.3}
      strokeWidth={HAIRLINE_STROKE_RATIO * HAIRLINE_EM}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : "true"}
      focusable="false"
      className={["hairline-wordmark", className].filter(Boolean).join(" ")}
    >
      {title ? <title>{title}</title> : null}
      {spec.paths.map((d) => (
        <path key={d.slice(0, 24)} d={d} />
      ))}
    </svg>
  );
}

