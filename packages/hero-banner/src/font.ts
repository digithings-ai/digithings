/** The font with a definition's overrides applied. */
export function fontWith(font: PixelFont, overrides?: Readonly<Record<string, Glyph>>): PixelFont {
  if (!overrides) return font;
  return { ...font, glyphs: { ...font.glyphs, ...overrides } };
}
