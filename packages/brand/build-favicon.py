#!/usr/bin/env python3
"""Bake favicon tiles from the brand-studio logo.

Digithings uses ``studio/logo-mark.svg`` in the default ink (accent is ink).
Digiquant uses the same mark with the quant up/down bands: accent faces take
``--up``, dim faces take ``--down``, then the studio face shade.

The live SVG is the favicon-32 preset (logo at 90% of the tile) so a tab
reads it. Larger rasters follow the studio presets: 78% at 192/512/180,
52% for the maskable icon. ``favicon-dg.svg`` stays the light tile and
``favicon-dg-light.svg`` the dark one — the filenames are reversed, and the
integrations chip loads the light file.

Usage:
    packages/brand/build-favicon.py
    packages/brand/build-favicon.py --check
"""

from __future__ import annotations

import argparse
import struct
import subprocess
import sys
from pathlib import Path

_BRAND_DIR = Path(__file__).resolve().parent
if str(_BRAND_DIR) not in sys.path:
    sys.path.insert(0, str(_BRAND_DIR))

from studio_compose import (  # noqa: E402
    DARK_BG,
    DARK_INK,
    LIGHT_BG,
    LIGHT_INK,
    frame,
    logo_mark_inner,
    place,
    quant_logo_inner,
)

BRAND = Path(__file__).resolve().parent
REPO_ROOT = BRAND.parents[1]

# (filename, pixel size, logo percent of the tile, polarity)
RASTERS = (
    ("digi-app-16.png", 16, 90, "dark"),
    ("digi-app-32.png", 32, 90, "dark"),
    ("digi-app-48.png", 48, 90, "dark"),
    ("digi-app-192.png", 192, 78, "dark"),
    ("digi-app-512.png", 512, 78, "dark"),
    ("digi-app-maskable-512.png", 512, 52, "dark"),
    ("digi-app-touch-dark.png", 180, 78, "dark"),
    ("digi-app-touch-light.png", 180, 78, "light"),
)

COMMENT = (
    "GENERATED by packages/brand/build-favicon.py — do not hand-edit. Logo from the brand studio."
)


def _palette(mode: str) -> tuple[str, str]:
    if mode == "dark":
        return DARK_BG, DARK_INK
    return LIGHT_BG, LIGHT_INK


def _logo(kind: str, mode: str) -> tuple[str, float, float]:
    if kind == "quant":
        return quant_logo_inner(mode)
    _bg, ink = _palette(mode)
    return logo_mark_inner(ink)


def tile_svg(kind: str, mode: str, size: int, logo_pct: float) -> str:
    bg, _ink = _palette(mode)
    inner, box_w, box_h = _logo(kind, mode)
    return frame(
        size,
        size,
        f'<rect width="{size}" height="{size}" fill="{bg}"/>',
        place(inner, box_w, box_h, size, size, logo_pct),
        comment=COMMENT,
    )


def site_svgs(kind: str) -> dict[str, str]:
    """Paths relative to the site ``public/`` directory."""
    icons = {
        "icons/digi-app-dark.svg": tile_svg(kind, "dark", 32, 90),
        "icons/digi-app-light.svg": tile_svg(kind, "light", 32, 90),
        # Polarity is in the file body, not the name. See the module docstring.
        "favicon-dg.svg": tile_svg(kind, "light", 32, 90),
        "favicon-dg-light.svg": tile_svg(kind, "dark", 32, 90),
    }
    return icons


def _png_size(blob: bytes) -> tuple[int, int]:
    if blob[12:16] != b"IHDR":
        raise SystemExit("png is missing an IHDR")
    width, height = struct.unpack(">II", blob[16:24])
    return width, height


def _write_ico(path: Path, pngs: list[bytes]) -> None:
    count = len(pngs)
    header = struct.pack("<HHH", 0, 1, count)
    entries = b""
    offset = 6 + 16 * count
    for blob in pngs:
        width, height = _png_size(blob)
        entries += struct.pack(
            "<BBBBHHII",
            width if width < 256 else 0,
            height if height < 256 else 0,
            0,
            0,
            1,
            32,
            len(blob),
            offset,
        )
        offset += len(blob)
    path.write_bytes(header + entries + b"".join(pngs))


def _raster(kind: str) -> dict[str, bytes]:
    """Render every PNG for one site. Keys are filenames under ``icons/`` plus ico sizes."""
    jobs = []
    for name, size, pct, mode in RASTERS:
        jobs.append((name, tile_svg(kind, mode, size, pct), size))
    script = r"""
const sharp = require("sharp"), fs = require("fs");
const jobs = JSON.parse(fs.readFileSync(0, "utf8"));
(async () => {
  const out = {};
  for (const job of jobs) {
    const png = await sharp(Buffer.from(job.svg)).png({ compressionLevel: 9 }).toBuffer();
    out[job.name] = png.toString("base64");
  }
  process.stdout.write(JSON.stringify(out));
})().catch((error) => { console.error(error.message); process.exit(1); });
"""
    import json

    payload = json.dumps([{"name": name, "svg": svg} for name, svg, _size in jobs])
    result = subprocess.run(
        ["node", "-e", script],
        input=payload,
        text=True,
        capture_output=True,
        cwd=REPO_ROOT,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(result.stderr.strip() or "sharp raster failed")
    encoded = json.loads(result.stdout)
    import base64

    return {name: base64.b64decode(data) for name, data in encoded.items()}


def destinations(kind: str) -> list[Path]:
    if kind == "mono":
        roots = [
            REPO_ROOT / "apps" / "digithings-web" / "public",
            REPO_ROOT / "apps" / "digichat" / "public",
        ]
    else:
        roots = [REPO_ROOT / "apps" / "digiquant-web" / "public"]
    return roots


def _expected_files(kind: str) -> dict[Path, str]:
    files: dict[Path, str] = {}
    svgs = site_svgs(kind)
    for root in destinations(kind):
        for rel, svg in svgs.items():
            files[root / rel] = svg
    return files


def check() -> int:
    stale = False
    for kind in ("mono", "quant"):
        for path, svg in _expected_files(kind).items():
            if not path.exists() or path.read_text(encoding="utf-8") != svg:
                print(f"❌  {path.relative_to(REPO_ROOT)} is stale — re-run build-favicon.py")
                stale = True
        for root in destinations(kind):
            ico = root / "favicon.ico"
            if not ico.exists():
                print(f"❌  missing {ico.relative_to(REPO_ROOT)}")
                stale = True
            for name, size, _pct, _mode in RASTERS:
                png = root / "icons" / name
                if not png.exists():
                    print(f"❌  missing {png.relative_to(REPO_ROOT)}")
                    stale = True
                    continue
                width, height = _png_size(png.read_bytes())
                if (width, height) != (size, size):
                    print(f"❌  {png.relative_to(REPO_ROOT)} is {width}x{height}, expected {size}")
                    stale = True
    chat_icon = REPO_ROOT / "apps" / "digichat" / "src" / "app" / "icon.svg"
    dark = site_svgs("mono")["icons/digi-app-dark.svg"]
    if not chat_icon.exists() or chat_icon.read_text(encoding="utf-8") != dark:
        print("❌  digichat icon.svg is stale — re-run build-favicon.py")
        stale = True
    if stale:
        return 1
    print("favicons: in sync ✅")
    return 0


def write() -> int:
    import shutil

    for kind in ("mono", "quant"):
        svgs = site_svgs(kind)
        pngs = _raster(kind)
        ico_names = ("digi-app-16.png", "digi-app-32.png", "digi-app-48.png")
        for root in destinations(kind):
            for rel, svg in svgs.items():
                target = root / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(svg, encoding="utf-8")
                print(f"wrote {target.relative_to(REPO_ROOT)}")
            for name, blob in pngs.items():
                target = root / "icons" / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(blob)
                print(f"wrote {target.relative_to(REPO_ROOT)}")
            _write_ico(root / "favicon.ico", [pngs[name] for name in ico_names])
            print(f"wrote {(root / 'favicon.ico').relative_to(REPO_ROOT)}")
    chat_icon = REPO_ROOT / "apps" / "digichat" / "src" / "app" / "icon.svg"
    chat_icon.write_text(site_svgs("mono")["icons/digi-app-dark.svg"], encoding="utf-8")
    touch = REPO_ROOT / "apps" / "digichat" / "public" / "icons" / "digi-app-touch-dark.png"
    apple = REPO_ROOT / "apps" / "digichat" / "src" / "app" / "apple-icon.png"
    shutil.copy2(touch, apple)
    print(f"wrote {chat_icon.relative_to(REPO_ROOT)}")
    print(f"wrote {apple.relative_to(REPO_ROOT)}")
    print("\nfavicons: rebuilt ✅")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # studio_compose is imported as a sibling. Running as a file needs that path.
    return check() if args.check else write()


if __name__ == "__main__":
    sys.path.insert(0, str(BRAND))
    raise SystemExit(main())
