#!/usr/bin/env python3
"""Cut the org/social avatar from the brand-studio logo.

The avatar is DERIVED, never drawn by hand. Its ink is ``studio/logo-mark.svg``,
the same Jenga the favicons bake, centred in the 100-unit box. GitHub renders
an avatar in a circle in several places, so the mark is scaled until the
60-unit box's corners land on a 43-unit radius — 50 less a 7-unit margin for
antialias spill and the ring GitHub draws.

The square is full-bleed with no baked corner radius: GitHub rounds avatars
itself, and a radius in the PNG shows as a seam inside its frame.

Usage:
    packages/brand/build-avatar.py          # writes avatar/*.png|svg
    packages/brand/build-avatar.py --check  # verify, write nothing
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

BRAND = Path(__file__).resolve().parent
# packages/brand sits one directory under the repo root (parents[0] is packages/).
REPO_ROOT = BRAND.parents[1]
SOURCE_TILE = BRAND / "studio" / "logo-mark.svg"
OUT_DIR = BRAND / "avatar"

LOGO_BOX = 60.0  # logo-mark.svg viewBox
SAFE_RADIUS = 43.0  # 50 minus a 7-unit margin; see the module docstring.

POLARITIES = {"dark": ("#0A0E0C", "#ECEEF0"), "light": ("#FBFBF9", "#14181B")}
SIZES = (1024, 500)

TEMPLATE = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="1024" height="1024">
  <!-- GENERATED by packages/brand/build-avatar.py — do not hand-edit.
       Ink is studio/logo-mark.svg, scaled so the 60-unit box's corners sit
       on a {radius}-unit radius (survives a circular crop) and centred. Square is
       full-bleed on purpose: GitHub rounds avatars itself. -->
  <rect width="100" height="100" fill="{bg}"/>
  <g transform="translate(50,50) scale({scale:.6f}) translate({dx:.4f},{dy:.4f})">
    {mark}
  </g>
</svg>
"""


def geometry() -> tuple[float, float, float]:
    """(scale, -cx, -cy) that centres the 60-unit box inside SAFE_RADIUS."""
    half_diagonal = ((LOGO_BOX / 2) ** 2 + (LOGO_BOX / 2) ** 2) ** 0.5
    return SAFE_RADIUS / half_diagonal, -LOGO_BOX / 2, -LOGO_BOX / 2


def logo_mark() -> str:
    source = SOURCE_TILE.read_text(encoding="utf-8")
    inner = re.sub(r"^[\s\S]*?<svg[^>]*>", "", source)
    inner = re.sub(r"</svg>\s*$", "", inner)
    if "currentColor" not in inner:
        raise SystemExit(f"no currentColor in {SOURCE_TILE} — has the mark changed shape?")
    return inner


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()

    scale, dx, dy = geometry()
    mark = logo_mark().replace('fill="currentColor"', 'fill="{ink}"')
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    svgs: dict[str, str] = {}
    for name, (bg, ink) in POLARITIES.items():
        svgs[name] = TEMPLATE.format(
            radius=int(SAFE_RADIUS),
            bg=bg,
            ink=ink,
            scale=scale,
            dx=dx,
            dy=dy,
            mark=mark.format(ink=ink),
        )

    if args.check:
        for name, svg in svgs.items():
            target = OUT_DIR / f"digithings-avatar-{name}.svg"
            if not target.exists() or target.read_text(encoding="utf-8") != svg:
                print(f"❌  {target.name} is stale — re-run build-avatar.py", file=sys.stderr)
                return 1
        print(f"avatar: in sync with {SOURCE_TILE.name} ✅")
        return 0

    for name, svg in svgs.items():
        (OUT_DIR / f"digithings-avatar-{name}.svg").write_text(svg, encoding="utf-8")

    # Raster via sharp, already a dependency of the frontend workspace.
    script = """
const sharp = require("sharp"), fs = require("fs"), path = process.argv[1];
const sizes = %s, names = %s;
(async () => {
  for (const n of names) {
    const svg = fs.readFileSync(`${path}/digithings-avatar-${n}.svg`);
    for (const s of sizes) {
      const suffix = s === 1024 ? "" : `-${s}`;
      const f = `${path}/digithings-avatar-${n}${suffix}.png`;
      await sharp(svg, { density: 600 }).resize(s, s).png({ compressionLevel: 9 }).toFile(f);
      console.log(`  ${f.split("/").pop()}  ${s}x${s}  ${(fs.statSync(f).size / 1024).toFixed(1)}KB`);
    }
  }
})().catch((e) => { console.error(e.message); process.exit(1); });
""" % (list(SIZES), list(POLARITIES))
    subprocess.run(["node", "-e", script, str(OUT_DIR)], cwd=REPO_ROOT, check=True)
    print(f"\navatar: rebuilt from {SOURCE_TILE.relative_to(REPO_ROOT)} ✅")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
