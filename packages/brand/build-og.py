#!/usr/bin/env python3
"""Cut the Open Graph link-preview cards for both sites.

An OG card is the only piece of brand art a person sees *before* they visit the
site — it renders in Slack, iMessage, LinkedIn, X, Discord, WhatsApp.

The cards follow the brand studio. Digithings uses the open-graph preset
(1200×630, field, dark, word-only, wordmark at 9% of the height) and the square
preset (1080×1080, wordmark at 5.5%) for summary cards. Digiquant uses the same
field with the quant-tinted logo, not the digithings word — a share card shows
one mark. The default theme's accent is ink, so the digithings card stays
monochrome.

``HEADLINES``, ``outline`` and the Geist Mono cursor constants stay in this
module because ``build-header.py`` still outlines the X and LinkedIn headers
from them. Those headers are not the link-preview cards.

Usage:
    packages/brand/build-og.py           # write the cards and the live copies
    packages/brand/build-og.py --check    # verify SVGs are in sync
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

BRAND = Path(__file__).resolve().parent
# packages/brand sits one directory under the repo root (parents[0] is packages/).
REPO_ROOT = BRAND.parents[1]
FONT = (
    REPO_ROOT / "node_modules" / "geist" / "dist" / "fonts" / "geist-mono" / "GeistMono-Regular.ttf"
)
OUT_DIR = BRAND / "og"

WIDTH, HEIGHT = 1200, 630  # the size every unfurler expects; og.png was already this
BG, INK, MUTE = "#0A0E0C", "#ECEEF0", "#8A9199"

# One character cell, matching TerminalMark's CURSOR constant.
CELL_EM = 0.6
CURSOR_H_EM = 0.71

WORD_EM = 116  # 11 cells at 0.6em = 766px, inside 1200 with room to breathe
LINE_EM = 30
DOMAIN_EM = 22

# Must track each site's own hero. If a hero changes, change this with it.
HEADLINES = {
    "digithings": {
        "word": "digithings",
        "line": "AI infrastructure in a glass box you own.",
        "domain": "digithings.ai",
    },
    "digiquant": {
        "word": "digiquant",
        "line": "A quant research desk in a glass box you own.",
        "domain": "digiquant.io",
    },
}


def _font() -> TTFont:
    if not FONT.exists():
        raise SystemExit(
            f"missing {FONT.relative_to(REPO_ROOT)} — run `npm install` first; the Geist "
            "fonts ship in the geist package, not in this repo"
        )
    font = TTFont(FONT)
    upem = font["head"].unitsPerEm
    advance = font["hmtx"]["d"][0]
    # The whole layout assumes a monospace 0.6em advance, the same number
    # `.term-cursor` is 0.6em wide for. Fail loudly if a font update changes it
    # rather than shipping a card with the cursor a fraction of a cell off.
    if round(advance / upem, 4) != CELL_EM:
        raise SystemExit(f"Geist Mono advance is {advance}/{upem}, expected {CELL_EM}em")
    return font


def outline(font: TTFont, text: str, em: float, x: float, baseline: float, fill: str) -> str:
    """`text` as embedded glyph paths, laid out on a monospace grid."""
    upem = font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = em / upem
    step = em * CELL_EM
    parts = []
    for index, char in enumerate(text):
        if char == " ":
            continue
        name = cmap.get(ord(char))
        if name is None:
            raise SystemExit(f"{char!r} is not in Geist Mono — pick different copy")
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        commands = pen.getCommands()
        if not commands:
            continue
        # y-flip: font units are y-up, SVG is y-down.
        parts.append(
            f'<g transform="translate({x + index * step:.2f} {baseline:.2f}) '
            f'scale({scale:.6f} {-scale:.6f})"><path d="{commands}" fill="{fill}"/></g>'
        )
    return "\n    ".join(parts)


def _studio():
    brand_dir = Path(__file__).resolve().parent
    if str(brand_dir) not in sys.path:
        sys.path.insert(0, str(brand_dir))
    import studio_compose

    return studio_compose


# Logo height on the digiquant card, as a percent of the 630px frame.
# The studio's logo-only layout is 60; 42 keeps the field visible around it.
QUANT_LOGO_PCT = 42


def _word_card(width: int, height: int, field: str, size_pct: float) -> str:
    studio = _studio()
    inner, box_w, box_h = studio.wordmark_inner(studio.DARK_INK)
    return studio.frame(
        width,
        height,
        f'<rect width="{width}" height="{height}" fill="{studio.DARK_BG}"/>',
        studio.field_layer(field, studio.DARK_INK, width, height),
        studio.place(inner, box_w, box_h, width, height, size_pct),
        comment=(
            "GENERATED by packages/brand/build-og.py — do not hand-edit. "
            "Brand-studio field, wordmark only."
        ),
    )


def _quant_card() -> str:
    studio = _studio()
    inner, box_w, box_h = studio.quant_logo_inner("dark")
    return studio.frame(
        WIDTH,
        HEIGHT,
        f'<rect width="{WIDTH}" height="{HEIGHT}" fill="{studio.DARK_BG}"/>',
        studio.field_layer("og", studio.DARK_INK, WIDTH, HEIGHT),
        studio.place(inner, box_w, box_h, WIDTH, HEIGHT, QUANT_LOGO_PCT),
        comment=(
            "GENERATED by packages/brand/build-og.py — do not hand-edit. "
            "Brand-studio field, digiquant logo only."
        ),
    )


def cards() -> dict[str, str]:
    """Stem → SVG. Stems are the filenames under ``og/`` without the suffix."""
    return {
        "digithings-og": _word_card(WIDTH, HEIGHT, "og", 9),
        "digithings-og-square": _word_card(1080, 1080, "square", 5.5),
        "digiquant-og": _quant_card(),
    }


def live_copies() -> list[tuple[Path, Path]]:
    public = REPO_ROOT / "apps"
    return [
        (OUT_DIR / "digithings-og.png", public / "digithings-web" / "public" / "og.png"),
        (OUT_DIR / "digiquant-og.png", public / "digiquant-web" / "public" / "og.png"),
        (
            OUT_DIR / "digithings-og-square.png",
            public / "digithings-web" / "public" / "og-square.png",
        ),
        (OUT_DIR / "digithings-og.png", public / "digichat" / "public" / "og.png"),
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rendered = cards()

    if args.check:
        for stem, svg in rendered.items():
            target = OUT_DIR / f"{stem}.svg"
            if not target.exists() or target.read_text(encoding="utf-8") != svg:
                print(f"❌  {target.name} is stale — re-run build-og.py", file=sys.stderr)
                return 1
        for src, dest in live_copies():
            if not src.exists() or not dest.exists() or src.read_bytes() != dest.read_bytes():
                print(
                    f"❌  {dest.relative_to(REPO_ROOT)} is stale — re-run build-og.py",
                    file=sys.stderr,
                )
                return 1
        print("og cards: in sync ✅")
        return 0

    for stem, svg in rendered.items():
        (OUT_DIR / f"{stem}.svg").write_text(svg, encoding="utf-8")

    script = """
const sharp = require("sharp"), fs = require("fs"), dir = process.argv[1];
const stems = %s;
(async () => {
  for (const stem of stems) {
    const svg = fs.readFileSync(`${dir}/${stem}.svg`);
    const f = `${dir}/${stem}.png`;
    await sharp(svg).png({ compressionLevel: 9 }).toFile(f);
    const m = await sharp(f).metadata();
    console.log(`  ${stem}.png  ${m.width}x${m.height}  ${(fs.statSync(f).size / 1024).toFixed(1)}KB`);
  }
})().catch((e) => { console.error(e.message); process.exit(1); });
""" % list(rendered)
    subprocess.run(["node", "-e", script, str(OUT_DIR)], cwd=REPO_ROOT, check=True)
    for src, dest in live_copies():
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(src.read_bytes())
        print(f"copied {dest.relative_to(REPO_ROOT)}")
    print("\nog cards: rebuilt ✅")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
