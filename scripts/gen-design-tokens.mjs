#!/usr/bin/env node
/**
 * Write packages/design/tokens.ts from the hex colours in tokens.css.
 *
 * Usage:
 *   node scripts/gen-design-tokens.mjs          # write the file
 *   node scripts/gen-design-tokens.mjs --check  # exit 1 if the file is stale
 *
 * Only literal hex colours are emitted, plus a one-step var() that points at
 * a hex in the same theme or in the unscoped :root block. rgba() and
 * unresolved var() stay in the CSS.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = join(root, "packages/design/tokens.css");
const outPath = join(root, "packages/design/tokens.ts");

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, "");
}

function sliceBlock(css, header) {
  const start = css.indexOf(header);
  if (start < 0) throw new Error(`missing block: ${header}`);
  const open = css.indexOf("{", start);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  throw new Error(`unclosed block: ${header}`);
}

function declarations(block) {
  const out = new Map();
  for (const match of block.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    out.set(match[1], match[2].trim());
  }
  return out;
}

function expandHex(raw) {
  const hex = raw.trim();
  if (!/^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i.test(hex)) return null;
  let body = hex.slice(1);
  if (body.length === 3) body = body.split("").map((c) => c + c).join("");
  return `#${body.toUpperCase()}`;
}

function resolve(value, theme, rootDecls) {
  const hex = expandHex(value);
  if (hex) return hex;
  const ref = value.match(/^var\((--[a-z0-9-]+)\)$/i);
  if (!ref) return null;
  const next = theme.get(ref[1]) ?? rootDecls.get(ref[1]);
  if (!next || next === value) return null;
  return expandHex(next) ?? resolve(next, theme, rootDecls);
}

function themeObject(decls, rootDecls) {
  const merged = new Map(decls);
  for (const [name, value] of rootDecls) {
    if (!name.startsWith("--accent-") || merged.has(name)) continue;
    merged.set(name, value);
  }
  const entries = [];
  for (const [name, value] of merged) {
    const hex = resolve(value, merged, rootDecls);
    if (!hex) continue;
    const key = name.slice(2).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
    entries.push([key, hex]);
  }
  entries.sort((a, b) => a[0].localeCompare(b[0]));
  return entries;
}

function render(dark, light) {
  const line = (entries) =>
    entries
      .map(([key, hex]) => `    ${key}: { hex: "${hex}", rgb: 0x${hex.slice(1).toLowerCase()} },`)
      .join("\n");
  return `// Generated by scripts/gen-design-tokens.mjs from packages/design/tokens.css.
// Do not edit. Run \`node scripts/gen-design-tokens.mjs\` after a colour change.

export const designTokens = {
  dark: {
${line(dark)}
  },
  light: {
${line(light)}
  },
} as const;

export type DesignTheme = keyof typeof designTokens;
export type DesignTokenName = keyof typeof designTokens.dark;
`;
}

const css = stripComments(readFileSync(cssPath, "utf8"));
const rootDecls = declarations(sliceBlock(css, ":root {"));
const dark = themeObject(declarations(sliceBlock(css, ':root[data-theme="dark"]')), rootDecls);
const light = themeObject(declarations(sliceBlock(css, ':root[data-theme="light"]')), rootDecls);
const text = render(dark, light);

if (process.argv.includes("--check")) {
  const current = readFileSync(outPath, "utf8");
  if (current !== text) {
    console.error("packages/design/tokens.ts is stale. Run: node scripts/gen-design-tokens.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(outPath, text);
}
console.log(`design tokens: ${dark.length} dark, ${light.length} light`);
