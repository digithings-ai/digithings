#!/usr/bin/env node
/**
 * Write packages/design/tokens.ts from packages/design/tokens.css.
 *
 * Each theme gets the colours that resolve under that theme: the bare :root
 * block, then the theme block, then the shared :root[data-theme] block.
 * Hex colours also carry a 24-bit integer. rgba() colours carry channels.
 *
 *   node scripts/gen-design-tokens.mjs           # write tokens.ts
 *   node scripts/gen-design-tokens.mjs --check   # exit 1 if tokens.ts is stale
 *   node scripts/gen-design-tokens.mjs --stdout  # print the file
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const cssPath = path.join(root, "packages/design/tokens.css");
const outPath = path.join(root, "packages/design/tokens.ts");

function stripComments(css) {
  let out = "";
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2);
      i = end === -1 ? css.length : end + 1;
      continue;
    }
    out += css[i];
  }
  return out;
}

function blockAfter(css, startMarker) {
  const start = css.indexOf(startMarker);
  if (start === -1) return "";
  let depth = 0;
  let i = css.indexOf("{", start);
  const open = i;
  for (; i < css.length; i++) {
    if (css[i] === "{") depth++;
    else if (css[i] === "}") {
      depth--;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  return "";
}

function declarations(block) {
  const props = new Map();
  const re = /--([a-z0-9-]+)\s*:\s*([^;]+);/gi;
  for (const match of block.matchAll(re)) {
    props.set(match[1], match[2].trim());
  }
  return props;
}

function parseHex(value) {
  const match = /^#([0-9a-f]{3}|[0-9a-f]{6}|[0-9a-f]{8})$/i.exec(value);
  if (!match) return null;
  let hex = match[1];
  if (hex.length === 3) {
    hex = hex
      .split("")
      .map((c) => c + c)
      .join("");
  }
  const rgb = hex.slice(0, 6);
  const color = {
    hex: `#${rgb.toUpperCase()}`,
    rgb24: Number.parseInt(rgb, 16),
  };
  if (hex.length === 8) color.a = Number.parseInt(hex.slice(6), 16) / 255;
  return color;
}

function parseRgba(value) {
  const match =
    /^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/i.exec(
      value,
    );
  if (!match) return null;
  return {
    r: Number(match[1]),
    g: Number(match[2]),
    b: Number(match[3]),
    a: match[4] === undefined ? 1 : Number(match[4]),
  };
}

function resolveColor(name, props, seen = new Set()) {
  if (seen.has(name)) return null;
  seen.add(name);
  const raw = props.get(name);
  if (!raw) return null;
  const asVar = /^var\(--([a-z0-9-]+)\)$/i.exec(raw);
  if (asVar) return resolveColor(asVar[1], props, seen);
  return parseHex(raw) ?? parseRgba(raw);
}

function themeColors(css, theme) {
  const merged = new Map([
    ...declarations(blockAfter(css, ":root {")),
    ...declarations(blockAfter(css, `:root[data-theme="${theme}"]`)),
    ...declarations(blockAfter(css, ":root[data-theme] {")),
  ]);
  const colors = {};
  for (const name of [...merged.keys()].sort()) {
    const color = resolveColor(name, merged);
    if (color) colors[name] = color;
  }
  return colors;
}

function emit(css) {
  const dark = themeColors(css, "dark");
  const light = themeColors(css, "light");
  const body = JSON.stringify({ dark, light }, null, 2);
  return `/* Generated by scripts/gen-design-tokens.mjs from packages/design/tokens.css. Do not edit. */\nexport const designTokens = ${body} as const;\nexport type DesignTokens = typeof designTokens;\n`;
}

const css = stripComments(readFileSync(cssPath, "utf8"));
const generated = emit(css);
const mode = process.argv[2];

if (mode === "--stdout") {
  process.stdout.write(generated);
} else if (mode === "--check") {
  const current = readFileSync(outPath, "utf8");
  if (current !== generated) {
    console.error("packages/design/tokens.ts is stale. Run node scripts/gen-design-tokens.mjs");
    process.exit(1);
  }
} else if (mode === undefined) {
  writeFileSync(outPath, generated);
} else {
  console.error(`unknown argument: ${mode}`);
  process.exit(2);
}
